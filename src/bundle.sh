# Keep the full generated source in memory before interactive input or installation.
# This also works when Bash reads the entry point from a pipe or /dev/fd.
write_bundle() {
  [[ $'\n'$1$'\n' != *$'\n__SB_MANAGER_PAYLOAD__\n'* ]] || return 1
  printf '%s\n' '#!/usr/bin/env bash' '# Generated by build.sh; edit src/, not this file.' \
    "IFS= read -r -d '' SB_BUNDLE_PAYLOAD <<'__SB_MANAGER_PAYLOAD__' || :" \
    "$1" '__SB_MANAGER_PAYLOAD__' \
    "SB_BUNDLE_PAYLOAD=\${SB_BUNDLE_PAYLOAD%\$'\\n'}" \
    'source <(printf "%s\n" "$SB_BUNDLE_PAYLOAD") || return 1 2>/dev/null || exit 1' \
    'if [[ ${BASH_SOURCE[0]:-} == "$0" || ${#BASH_SOURCE[@]} == 0 ]]; then main "$@"; exit $?; fi'
}
